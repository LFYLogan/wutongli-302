/* ===========================================================
   组合台词工具
   根据「我的性别 × 攻略对象性别」返回一句贴合处境的话。
   文本里照常可以写 {ta} / {mcTa}，引擎会替换。

     comboLine({ 'm|f': '…', 'f|m': '…', default: '…' })
     withCombo(lines, map)   // 并进段落数组，null 自动忽略
   =========================================================== */
function comboLine(map) {
  var s = G.getState();
  var key = (s.mcGender || 'x') + '|' + (s.loveGender || 'f');
  var v = map[key];
  if (v === undefined) v = map['default'];
  return v == null ? null : v;
}

function withCombo(lines, map) {
  var extra = comboLine(map);
  return extra ? lines.concat([extra]) : lines;
}
