function c3Visited(s, id) {
  return (s && s.visited && s.visited[id]) || 0;
}
function c3Stress(s, kind) {
  if (!s || (s.stress || 0) < 75) return null;
  if (kind === 'lift') return '你在电梯里站了很久。门开了又关，你才想起来自己忘了按楼层。';
  if (kind === 'ear') return '耳朵里有一阵很细的耳鸣，像老电视待机的声音。你咽了口口水，它才小下去。';
  if (kind === 'hand') return '你的手在抖。不是很明显的那种——是端着一杯水的时候，水面一直在动。';
  if (kind === 'food') return '你想不起来今天吃过什么。胃是空的，但不饿，只是发凉。';
  return '你吸了一口气，肋骨那里有点疼。';
}

